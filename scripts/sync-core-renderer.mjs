#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WEB_RENDERER_PATH = path.join(ROOT, "implementations", "web", "palembang.js");
const CORE_RENDERER_PATH = path.join(ROOT, "packages", "core", "src", "renderer.js");
const START = "/**\n * Palembang browser renderer.";
const END = "/**\n * Resolve the token URLs";

const webSource = readFileSync(WEB_RENDERER_PATH, "utf8");
const start = webSource.indexOf(START);
const end = webSource.indexOf(END);
if (start < 0 || end < 0 || end <= start) {
  throw new Error("could not locate the pure renderer section in implementations/web/palembang.js");
}

const renderer = "// GENERATED FILE. Do not edit by hand.\n// Source: implementations/web/palembang.js\n\n" + webSource
  .slice(start, end)
  .replace(/\nconst CANDIDATE_TOKEN_URLS = .*?;\n/, "\n")
  .replace("Generated by the Palembang Playground", "Generated by the Palembang renderer")
  .replace(/\n+$/, "\n");

if (process.argv.includes("--check")) {
  const existing = readFileSync(CORE_RENDERER_PATH, "utf8");
  if (existing !== renderer) {
    console.error(`${path.relative(ROOT, CORE_RENDERER_PATH)} is stale; run node scripts/sync-core-renderer.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(CORE_RENDERER_PATH, renderer, "utf8");
}
